'use strict';
const assert=require('node:assert/strict');
const reader=require('./degiro_morning_reader.js'),evidence=require('./degiro_android_bridge.js');
const at='2026-10-28T11:00:00Z',isin='DE000FD0S0G4';
const list={listUploadedAt:at,products:[{isin}]};
assert.deepEqual(reader.listPayload(list,evidence,Date.parse(at)),{listUploadedAt:'2026-10-28T11:00:00.000Z',isins:[isin]});
for(const bad of [{...list,listUploadedAt:'invalid'},{...list,products:[{isin},{isin}]},{...list,products:[{isin:'DE0000000000'}]}])assert.throws(()=>reader.listPayload(bad,evidence,Date.parse(at)));
assert.throws(()=>reader.listPayload(list,evidence,Date.parse(at)+86400001));
const draft=['BOB APP-LESEENTWURF – NICHT VERIFIZIERT','ISIN: '+isin,'Quelle: DEGIRO-App','Erfasst: '+at,'Währung (Anzeige ungeprüft): EUR','Geld (Anzeige ungeprüft): 13,06','Brief (Anzeige ungeprüft): 13,07','Hinweis (Anzeige ungeprüft): Keine Aussage zur Handelbarkeit','Kein automatischer Handelsnachweis, keine Freigabe, keine Order.'].join('\n');
const run={batchId:'a'.repeat(32),revision:4,listUploadedAt:at,isins:[isin],results:[{isin,attempts:2,draft,code:'PARTIAL'}],events:[]};
assert.deepEqual(reader.decode(reader.encode(run)),run);
assert.equal(reader.validateRun(run,evidence),run);
assert.throws(()=>reader.validateRun({...run,results:[{...run.results[0],isin:'DE000FG77MY4'}]},evidence));
const values=new Map(),storage={getItem:k=>values.get(k)||null,setItem:(k,v)=>values.set(k,v),removeItem:k=>values.delete(k)};
reader.keep(storage,run);
assert.throws(()=>reader.keep(storage,{...run,batchId:'b'.repeat(32)}));
assert.throws(()=>reader.acknowledge(storage,run,{ok:true,saved:true,batchId:run.batchId,revision:3}));
assert.ok(storage.getItem(reader.KEY));
const newer={...run,revision:5};reader.keep(storage,newer);
reader.acknowledge(storage,run,{ok:true,saved:true,batchId:run.batchId,revision:4});
assert.equal(JSON.parse(storage.getItem(reader.KEY)).revision,5);
reader.acknowledge(storage,newer,{ok:true,saved:true,batchId:run.batchId,revision:5});
assert.equal(storage.getItem(reader.KEY),null);
assert.throws(()=>reader.keep({getItem:()=>null,setItem:()=>{throw Error('quota');}},run));
assert.throws(()=>reader.decode('!invalid'));
console.log('Morning reader: dated list, exact identity, durable versioned outbox and ACK guards passed.');
